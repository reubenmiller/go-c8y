func readConfig(t *testing.T) *viper.Viper {
	// Read configuration
	config := viper.New()
	config.SetConfigName("application")
	config.AddConfigPath(".")
	err := config.ReadInConfig()

	if err != nil {
		slog.Warn("Could not read configuration file")
	}

	// Set default settings
	config.SetDefault("report.concurrency", 20)
	config.SetDefault("log.file", "application.log")

	// Enable all variables to be defined as (case-sensitive) environment variables in the form of
	config.SetEnvKeyReplacer(strings.NewReplacer(".", "_"))
	config.AutomaticEnv()

	// Add extra aliases for Cumulocity Microservice SDK Specific environment variables
	config.BindEnv("c8y.host", "C8Y_BASEURL")
	config.BindEnv("c8y.tenant", "C8Y_BOOTSTRAP_TENANT")
	config.BindEnv("c8y.username", "C8Y_BOOTSTRAP_USER")
	config.BindEnv("c8y.username", "C8Y_USER")
	config.BindEnv("c8y.password", "C8Y_BOOTSTRAP_PASSWORD")
	config.BindEnv("c8y.token", "C8Y_TOKEN")

	requiredProperties := []string{
		"c8y.host",
		"c8y.tenant",
		"c8y.username",
		// "c8y.password",
	}

	// The microservice tests require a live Cumulocity tenant. When the
	// credentials are not configured (e.g. forked PRs without secrets), skip
	// the test rather than panicking so the suite stays green for contributors.
	if missing := MissingConfiguration(config, requiredProperties...); len(missing) > 0 {
		t.Skipf("skipping live microservice test: missing required configuration: %s", strings.Join(missing, ", "))
	}

	return config
}

// MissingConfiguration returns the subset of props that are not set in the
// given configuration.
func MissingConfiguration(config *viper.Viper, props ...string) []string {
	missingProps := []string{}
	for _, prop := range props {
		if config.GetString(prop) == "" {
			missingProps = append(missingProps, prop)
		}
	}
	return missingProps
}

// testApplicationPrefix is the name prefix of the randomly named applications
// created by BootstrapApplication
const testApplicationPrefix = "ci-test"

// staleTestApplication matches the names generated by BootstrapApplication
var staleTestApplication = regexp.MustCompile("^" + testApplicationPrefix + "[a-z0-9]{5}$")

var sweepStaleApplicationsOnce sync.Once

// sweepStaleTestApplications deletes applications left behind by previous
// test runs which were not able to clean up after themselves (e.g. the test
// binary was killed by a timeout, or the delete request failed).
// The live tests are serialised per tenant, so no other run can still be
// using these applications.
func sweepStaleTestApplications(t *testing.T, client *api.Client) {
	ctx := context.Background()
	items := client.Microservices.ListAll(ctx, microservices.ListOptions{
		Owner: client.Auth.Tenant,
	})
	for item := range items.Items() {
		if !staleTestApplication.MatchString(item.Name()) {
			continue
		}
		t.Logf("Deleting stale test application. name=%s, id=%s", item.Name(), item.ID())
		if result := client.Microservices.Delete(ctx, item.ID(), applications.DeleteOptions{Force: true}); result.Err != nil {
			t.Logf("Could not delete stale test application. name=%s, id=%s, err=%s", item.Name(), item.ID(), result.Err)
		}
	}
	if err := items.Err(); err != nil {
		t.Logf("Could not list stale test applications. err=%s", err)
	}
}

// deleteTestApplication deletes the application (by ID or resolver string)
// and reports a test error if it could not be deleted, so leaked applications
// do not go unnoticed
func deleteTestApplication(t *testing.T, client *api.Client, id string) {
	result := client.Microservices.Delete(context.Background(), id, applications.DeleteOptions{
		Force: true,
	})
	if result.Err != nil {
		t.Errorf("Could not delete test application. id=%s, err=%s", id, result.Err)
	}
}

// BootstrapApplication creates an application
func BootstrapApplication(t *testing.T, appName ...string) *microservice.Microservice {
	config := readConfig(t)

	var applicationName string

	if len(appName) == 0 {
		applicationName = testApplicationPrefix + strings.ToLower(testingutils.RandomString(5))
	} else {
		applicationName = appName[0]
	}

	host := config.GetString("c8y.host")
	tenant := config.GetString("c8y.tenant")
	username := config.GetString("c8y.username")

	slog.Info("Bootstrapping application", "host", host, "tenant", tenant, "username", username)

	client := CreateTestClientBasicAuth(t)

	sweepStaleApplicationsOnce.Do(func() {
		sweepStaleTestApplications(t, client)
	})

	app := client.Microservices.Create(
		context.Background(),
		model.NewMicroservice(applicationName),
	)

	if app.Err != nil {
		// The application may still have been created (e.g. the request timed
		// out after the server processed it), so try to remove it by name
		deleteTestApplication(t, client, client.Microservices.ByName(applicationName))
		t.Fatalf("Could not create application. err=%s", app.Err)
	}

	t.Cleanup(func() {
		deleteTestApplication(t, client, app.Data.ID())
	})

	// Set required roles
	appUpdate := client.Applications.Update(
		context.Background(),
		app.Data.ID(),
		&model.Application{
			RequiredRoles: []string{
				"ROLE_INVENTORY_READ",
				"ROLE_INVENTORY_CREATE",
				"ROLE_INVENTORY_ADMIN",
				"ROLE_IDENTITY_READ",
				"ROLE_IDENTITY_ADMIN",
				"ROLE_AUDIT_READ",
				"ROLE_AUDIT_ADMIN",
				"ROLE_MEASUREMENT_READ",
				"ROLE_MEASUREMENT_ADMIN",
				"ROLE_EVENT_READ",
				"ROLE_EVENT_ADMIN",
				"ROLE_ALARM_ADMIN",
				"ROLE_ALARM_READ",
				"ROLE_DEVICE_CONTROL_READ",
				"ROLE_DEVICE_CONTROL_ADMIN",
			},
		},
	)

	if appUpdate.Err != nil {
		slog.Error("Could not update microservice's requiredRoles", "err", appUpdate.Err)
		t.FailNow()
	}

	// Subscribe to application
	result := client.Microservices.Subscribe(
		context.Background(),
		client.Auth.Tenant,
		app.Data.Self(),
	)

	if result.Err != nil {
		slog.Error("Could not subscribe to application", "err", result.Err)
		t.FailNow()
	}

	// Get Microservice Credentials
	appCredentials := client.Microservices.BootstrapUser.Get(
		context.Background(),
		app.Data.ID(),
	)

	if appCredentials.Err != nil {
		slog.Error("Could not get application credentials", "err", appCredentials.Err)
		t.FailNow()
	}

	// Set microservice env variables
	os.Setenv(microservices.EnvironmentApplicationName, applicationName)
	os.Setenv(microservices.EnvironmentBootstrapTenant, appCredentials.Data.Tenant())
	os.Setenv(microservices.EnvironmentBootstrapUsername, appCredentials.Data.Username())
	os.Setenv(microservices.EnvironmentBootstrapPassword, appCredentials.Data.Password())
	// os.Unsetenv("C8Y_TOKEN")

	ms := microservice.New(microservice.Options{})

	if err := ms.Bootstrap(context.Background()); err != nil {
		slog.Error("Microservice bootstrap failed", "err", err)
		t.FailNow()
	}

	if err := ms.TestClientConnection(); err != nil {
		slog.Error("Microservice test connection failed", "err", err)
		t.FailNow()
	}

	t.Cleanup(func() {
		client.Devices.Delete(context.Background(), ms.AgentID, managedobjects.DeleteOptions{})
	})

	return ms
}
